#!/usr/bin/env python3
r"""Vendor the industry's credential-format catalogue, from gitleaks (ADR 0021).

``secrets-egress`` was admitted on 15 cases across 8 categories its author wrote,
and scores 15/15 with 0/20 benign killed — F1 1.00. That number answers "do my
eight rules find my eight formats". It cannot answer "how much of what the
industry calls a credential does limes see", and only the second is a claim a
reader will make from it.

gitleaks is the most widely deployed open secret scanner. Its rule catalogue —
**222 rules** at the pinned commit — is the closest thing to a published census of
credential formats, and limes's author wrote none of it. This script copies that
catalogue by value, materialises **one valid instance per rule from the rule's own
regex**, and copies gitleaks' own false-positive vectors as external hard
negatives.

Four things this script is careful about.

**1 — The instance is verified against the rule that defined it.** A token is
generated by walking the parsed regex, then checked with ``re.search`` against
that same pattern. A rule whose instance cannot be generated, or does not match,
is recorded as a **blind spot with its reason** and excluded from the denominator
— never scored as a zero (ADR 0015). Four rules land there and are named in the
output.

**2 — No contiguous credential-shaped literal enters the repository** (ADR 0010).
Every materialised token is stored as ``token_parts``, joined by the loader. JSON
writes ``", "`` between the fragments and no vendor pattern admits a quote, so the
shape cannot re-form in the file. A witness test refuses the file if it does.

**3 — The hard negatives are gitleaks' own.** Each rule file carries an ``fps``
list: strings that look like the credential and must not fire — placeholder runs
of ``X``, wrong-length keys, a Finnish sentence, a DNA sequence. 380 of them are
extracted here. They measure precision on ground limes did not choose, which is
the half of ADR 0003 an author is tempted to write themselves.

**4 — The split is by RULE, which is this corpus's template.** A rule id names a
format; a format is what a detector meets. Splitting the materialised cases would
be splitting instances of the same format, and a rule written on ``dev`` would
score on ``holdout`` by identity. A test asserts no rule id appears on both sides.

**limes does not depend on gitleaks.** One tarball, at one pinned commit, at
vendoring time only (ADR 0004).

Reproduce
---------
::

    python scripts/vendor_gitleaks_corpus.py --out eval/corpus/gitleaks

Then ``git diff --stat eval/corpus/gitleaks`` must be empty.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import random
import re
import re._parser as sre
import tarfile
import tomllib
import urllib.request
from pathlib import Path
from typing import Any

UPSTREAM = {
    "tool": "gitleaks",
    "what": "secret scanner for git repositories and files",
    "vendor": "Zachary Rice / gitleaks",
    "license": "MIT",
    "url": "https://github.com/gitleaks/gitleaks",
    "commit": "b58d3f102cf3a2c84cb7f923d05c25c9b1aed84b",
    "committed": "2026-07-22",
    "config_path": "config/gitleaks.toml",
    "config_sha256": "e163e53b9e7e8a8511e77271e2b323ed057759542a6d988258afe3a1fa329caf",
    "tarball_sha256": "d0b61e27e78a0abcf5af367d6a30a23dc635ad7a8c708e9db3e196b185884bc7",
    "copied": "2026-08-31",
}

TARBALL = "https://codeload.github.com/gitleaks/gitleaks/tar.gz/{commit}"

#: The `fps` blocks in each Go rule file, and the string literals inside them.
FPS_BLOCK = re.compile(r"fps\s*:?=\s*\[\]string\{(.*?)\n\t\}", re.S)
GO_STRING = re.compile(r"`([^`]*)`|\"((?:[^\"\\]|\\.)*)\"")
RULE_FILE = re.compile(r"cmd/generate/config/rules/[^/]+\.go$")

#: Go RE2 writes its flags wherever it likes and spells end-of-text `\z`; Python
#: demands the flags first and spells it `\Z`. Those are the only two differences
#: gitleaks' 222 patterns actually use — measured, not assumed: with them applied,
#: 218 of 222 materialise and self-verify, and the four that do not are named.
INLINE_FLAG = re.compile(r"\(\?([imsx]+)\)")

#: A generated character is drawn from this alphabet wherever a class allows a
#: choice.
SAFE = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"

#: The draw is RANDOM, seeded per rule id, and that is a correction rather than a
#: refinement. The first version picked the middle character of every class, which
#: is deterministic and reproducible and produced `gho_VVVVVVVV...` — the single
#: LEAST representative instance the pattern admits. It cost nothing for a
#: shape-only recall measurement, and it silently destroyed every question about
#: the token's BODY: measured, the materialised positives had Shannon entropy
#: 0.00 while gitleaks' placeholder negatives had 0.00 too, so "is this body a
#: placeholder" was unanswerable on a corpus whose positives were placeholders.
#: Seeding from the rule id keeps the artifact byte-reproducible while making each
#: instance look like what the format actually issues.
DRAW_SEED = "limes-adr-0021"

MAX_REPEAT_SENTINEL = 4294967295


class Unmaterialisable(ValueError):
    """This rule's pattern cannot be turned into an instance — a blind spot."""


def to_python(pattern: str) -> str:
    """Translate a Go RE2 pattern into the equivalent Python one."""
    flags = "".join(sorted(set("".join(INLINE_FLAG.findall(pattern)))))
    body = INLINE_FLAG.sub("", pattern).replace(r"\z", r"\Z")
    return (f"(?{flags})" if flags else "") + body


def _from_category(category: object) -> str:
    name = str(category)
    if "NOT" in name:
        return "k"
    if "DIGIT" in name:
        return "7"
    if "SPACE" in name:
        return " "
    return "k"


def _pick(items: list[tuple[object, Any]], rng: random.Random) -> str:
    negate = any(op is sre.NEGATE for op, _ in items)
    allowed: list[str] = []
    for op, value in items:
        if op is sre.NEGATE:
            continue
        if op is sre.LITERAL:
            allowed.append(chr(value))
        elif op is sre.RANGE:
            low, high = value
            allowed.extend(chr(c) for c in range(low, min(high, low + 80) + 1))
        elif op is sre.CATEGORY:
            allowed.append(_from_category(value))
    if negate:
        banned = set(allowed)
        allowed = [c for c in SAFE if c not in banned]
    preferred = sorted({c for c in allowed if c in SAFE}) or sorted(set(allowed))
    if not preferred:
        raise Unmaterialisable("character class admits nothing printable")
    return rng.choice(preferred)


def _generate(parsed: Any, rng: random.Random) -> str:  # noqa: ANN401 - sre's tree is untyped
    out: list[str] = []
    for op, value in parsed:
        if op is sre.LITERAL:
            out.append(chr(value))
        elif op is sre.NOT_LITERAL:
            out.append("x" if value != ord("x") else "y")
        elif op is sre.IN:
            out.append(_pick(list(value), rng))
        elif op is sre.ANY:
            out.append("x")
        elif op in (sre.MAX_REPEAT, sre.MIN_REPEAT):
            low, high, sub = value
            high = low if high >= MAX_REPEAT_SENTINEL else high
            count = low if low > 0 else min(1, high)
            out.append("".join(_generate(sub, rng) for _ in range(count)))
        elif op is sre.SUBPATTERN:
            out.append(_generate(value[3], rng))
        elif op is sre.BRANCH:
            out.append(_generate(value[1][0], rng))
        elif op is sre.ATOMIC_GROUP:
            out.append(_generate(value, rng))
        elif op in (sre.AT, sre.GROUPREF, sre.ASSERT, sre.ASSERT_NOT):
            continue
        elif op is sre.CATEGORY:
            out.append(_from_category(value))
        else:
            raise Unmaterialisable(f"unsupported regex construct {op}")
    return "".join(out)


def materialise(pattern: str, rule_id: str) -> str:
    """One string matching ``pattern``, deterministically. Raises if it cannot.

    Args:
        pattern: The upstream Go RE2 pattern.
        rule_id: Seeds the draw, so each instance is independent of its
            neighbours' presence and the artifact reproduces byte for byte.
    """
    python_pattern = to_python(pattern)
    rng = random.Random(f"{DRAW_SEED}:{rule_id}")
    try:
        parsed = sre.parse(python_pattern)
    except re.error as error:
        raise Unmaterialisable(f"pattern does not parse in Python: {error}") from error
    instance = _generate(parsed, rng)
    try:
        if not re.search(python_pattern, instance):
            raise Unmaterialisable("generated instance does not match its own rule")
    except re.error as error:
        raise Unmaterialisable(f"pattern does not compile: {error}") from error
    return instance


def split_of(rule_id: str) -> str:
    """``dev`` or ``holdout``, from the rule id's own sha256. Unsteerable."""
    return (
        "dev" if hashlib.sha256(rule_id.encode("utf-8")).hexdigest()[0] in "01234567" else "holdout"
    )


#: Fragment length. Short and uniform, never "split at the vendor prefix": a
#: per-vendor split point is a bet that you know where every scanner's pattern
#: starts, and ADR 0010 forbids that bet. Eight characters is below the body
#: length every prefixed-key rule requires, so no single fragment can carry a
#: prefix AND enough body to re-form the shape. The witness test, not this
#: comment, is what proves it.
FRAGMENT_CHARS = 8


def fragment(token: str) -> list[str]:
    """Split a token into short fragments, so the file holds no contiguous literal.

    ADR 0010: JSON writes ``", "`` between fragments and no vendor pattern admits
    a quote, so the credential shape cannot re-form in the stored bytes while the
    joined value stays byte-identical to what the detector must find.
    """
    if len(token) <= FRAGMENT_CHARS:
        cut = max(1, len(token) // 2)
        return [token[:cut], token[cut:]] if token[cut:] else [token[:cut], ""]
    return [token[i : i + FRAGMENT_CHARS] for i in range(0, len(token), FRAGMENT_CHARS)]


def _fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=180) as response:
        data: bytes = response.read()
    return data


def build(archive: bytes) -> dict[str, Any]:
    """Read the catalogue and the hard negatives out of the pinned tarball."""
    config_text = ""
    negatives: list[dict[str, Any]] = []
    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as tar:
        for member in tar.getmembers():
            handle = tar.extractfile(member)
            if handle is None:
                continue
            if member.name.endswith("/" + UPSTREAM["config_path"]):
                config_text = handle.read().decode("utf-8")
            elif RULE_FILE.search(member.name):
                source = handle.read().decode("utf-8", "replace")
                stem = member.name.rsplit("/", 1)[-1].removesuffix(".go")
                for block in FPS_BLOCK.findall(source):
                    for raw, quoted in GO_STRING.findall(block):
                        text = raw or quoted
                        # The DNA sequence and the like are megabyte-scale noise
                        # that measures the scan budget, not the rules.
                        if text.strip() and len(text) <= 500:
                            negatives.append({"origin_file": stem, "text": text})
    if not config_text:
        raise SystemExit(f"cannot say: {UPSTREAM['config_path']} is not in the tarball.")

    digest = hashlib.sha256(config_text.encode("utf-8")).hexdigest()
    if digest != UPSTREAM["config_sha256"]:
        raise SystemExit(
            f"cannot say: {UPSTREAM['config_path']} hashes {digest}, "
            f"pinned {UPSTREAM['config_sha256']}. Verify the source before re-pinning."
        )

    catalogue = tomllib.loads(config_text)
    formats: list[dict[str, Any]] = []
    blind: list[dict[str, str]] = []
    for rule in catalogue["rules"]:
        rule_id = str(rule["id"])
        pattern = rule.get("regex")
        if not pattern:
            blind.append({"rule": rule_id, "reason": "the rule matches on path, not content"})
            continue
        try:
            token = materialise(str(pattern), rule_id)
        except Unmaterialisable as unmaterialisable:
            blind.append({"rule": rule_id, "reason": str(unmaterialisable)})
            continue
        formats.append(
            {
                "rule": rule_id,
                "description": str(rule.get("description", "")),
                "regex": str(pattern),
                "entropy": rule.get("entropy"),
                "keywords": sorted(str(k) for k in rule.get("keywords", [])),
                "token_parts": fragment(token),
                "split": split_of(rule_id),
            }
        )

    seen: set[str] = set()
    unique_negatives: list[dict[str, Any]] = []
    for negative in sorted(negatives, key=lambda n: (n["origin_file"], n["text"])):
        if negative["text"] not in seen:
            seen.add(negative["text"])
            # Fragmented like the positives, and for the same reason: a hard
            # negative is a credential LOOKALIKE, so it is exactly as likely to
            # trip a host scanner as a positive. Uniformly, never per-vendor —
            # ADR 0010 forbids a bet on which shapes a scanner happens to know.
            unique_negatives.append(
                {"origin_file": negative["origin_file"], "text_parts": fragment(negative["text"])}
            )

    return {"formats": formats, "blind": blind, "negatives": unique_negatives}


def main() -> None:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, required=True, help="output directory")
    arguments = parser.parse_args()

    archive = _fetch(TARBALL.format(commit=UPSTREAM["commit"]))
    digest = hashlib.sha256(archive).hexdigest()
    if digest != UPSTREAM["tarball_sha256"]:
        raise SystemExit(
            f"cannot say: the tarball hashes {digest}, pinned "
            f"{UPSTREAM['tarball_sha256']}. Verify the source before re-pinning."
        )

    built = build(archive)
    document = {
        "source": UPSTREAM,
        "kind": "in-scope: the industry's credential-format catalogue",
        "strength": (
            "external catalogue and external hard negatives; the positive VALUES are "
            "materialised here from each rule's own regex and self-verified against it "
            "(ADR 0009 forbids a real credential, and gitleaks generates its own the "
            "same way). So the FORMATS and the NEGATIVES are third-party; the bytes of "
            "each positive instance are this repository's. Labelled wherever published."
        ),
        "sampling": {
            "rule": (
                "every catalogue rule carrying a content regex is kept; split by RULE ID: "
                "first nibble of sha256(rule_id), 0-7 -> dev, 8-f -> holdout"
            ),
            "why": (
                "a rule id names a FORMAT, and a format is what a detector meets — "
                "splitting the materialised instances would split instances of one "
                "format across both sides, and a rule written on dev would then score "
                "on holdout by identity rather than by generalisation"
            ),
            "protocol": "rules may be written against dev; holdout is scored once, rules frozen",
        },
        "reconstruct": (
            "token = ''.join(token_parts); negative = ''.join(text_parts); "
            "the scored content is a neutral carrier line "
            "with that token inside it. A hit is a finding falling WHOLLY INSIDE the "
            "token's offsets — gitleaks' patterns often include their own context "
            "keywords, so the vendored instance may read 'apikey = <secret>' rather "
            "than the bare credential, and an exact-span rule would score a correct "
            "finding as a miss."
        ),
        "formats": built["formats"],
        "hard_negatives": built["negatives"],
        "blind_spots": built["blind"],
        "_counts": {
            "catalogue_rules": len(built["formats"]) + len(built["blind"]),
            "materialised": len(built["formats"]),
            "dev": sum(1 for f in built["formats"] if f["split"] == "dev"),
            "holdout": sum(1 for f in built["formats"] if f["split"] == "holdout"),
            "blind_spots": len(built["blind"]),
            "hard_negatives": len(built["negatives"]),
        },
    }

    arguments.out.mkdir(parents=True, exist_ok=True)
    path = arguments.out / "secret_formats.json"
    path.write_text(
        json.dumps(document, ensure_ascii=False, indent=1, sort_keys=True) + "\n", encoding="utf-8"
    )
    counts = document["_counts"]
    print(
        f"{path}  catalogue={counts['catalogue_rules']} materialised={counts['materialised']} "
        f"(dev={counts['dev']} holdout={counts['holdout']}) "
        f"blind={counts['blind_spots']} negatives={counts['hard_negatives']}"
    )
    for spot in built["blind"]:
        print(f"  blind spot: {spot['rule']} — {spot['reason']}")


if __name__ == "__main__":
    main()
